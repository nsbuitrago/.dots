local mainMod = "SUPER" -- Sets "Windows" key as main modifier

-- Example binds, see https://wiki.hypr.land/Configuring/Basics/Binds/ for more
hl.bind(mainMod .. "+Space", hl.dsp.exec_cmd("vicinae toggle"))

hl.bind(mainMod .. " + Return", hl.dsp.exec_cmd(terminal))

-- Focus an existing browser window, including one on another workspace;
-- launch Brave only when no matching window exists.
local function launchOrFocus(command, class)
    local windows = hl.get_windows({ class = class })

    if #windows > 0 then
        hl.dispatch(hl.dsp.focus({ window = windows[1] }))
    else
        hl.exec_cmd(command)
    end
end

hl.bind(mainMod .. " + B", function()
    launchOrFocus(browser, browserClass)
end)
-- Ask the focused application to open a new window. This uses the active
-- application's own Ctrl+N behavior rather than hard-coding an application.
hl.bind(mainMod .. " + N", hl.dsp.exec_cmd("hyprctl dispatch sendshortcut CTRL, N, activewindow"))
hl.bind(mainMod .. " + Z", hl.dsp.exec_cmd(editor))

local closeWindowBind = hl.bind(mainMod .. " + W", hl.dsp.window.close())
-- closeWindowBind:set_enabled(false)
